CREATE TABLE reservation_approval_recovery_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_preparation_id BIGINT NOT NULL REFERENCES reservation_payment_tx(id),
    status VARCHAR(32) NOT NULL,
    lookup_until TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    next_lookup_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lease_token UUID,
    lease_expires_at TIMESTAMP(6) WITH TIME ZONE,
    failure_count INTEGER NOT NULL DEFAULT 0,
    last_failure VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_approval_recovery_preparation UNIQUE (payment_preparation_id),
    CONSTRAINT ck_approval_recovery_status CHECK (status IN ('PENDING', 'COMPLETED', 'NOT_FOUND', 'NEEDS_REVIEW')),
    CONSTRAINT ck_approval_recovery_lease CHECK (
        (lease_token IS NULL AND lease_expires_at IS NULL)
        OR (status = 'PENDING' AND lease_token IS NOT NULL AND lease_expires_at IS NOT NULL)
    ),
    CONSTRAINT ck_approval_recovery_failures CHECK (
        (failure_count = 0 AND last_failure IS NULL)
        OR (failure_count > 0 AND last_failure IS NOT NULL)
    )
);

CREATE INDEX idx_approval_recovery_due
    ON reservation_approval_recovery_jobs (next_lookup_at, id)
    WHERE status = 'PENDING';

-- 주문 결과를 아직 저장하지 않은 준비 이력도 조회 대상으로 옮긴다.
INSERT INTO reservation_approval_recovery_jobs (
    payment_preparation_id, status, lookup_until, next_lookup_at, failure_count, last_failure
)
SELECT preparation.id,
       CASE WHEN preparation.requested_payment_key IS NULL THEN 'NEEDS_REVIEW' ELSE 'PENDING' END,
       reservation.expires_at + INTERVAL '2 minutes',
       CURRENT_TIMESTAMP + INTERVAL '5 seconds',
       CASE WHEN preparation.requested_payment_key IS NULL THEN 1 ELSE 0 END,
       CASE WHEN preparation.requested_payment_key IS NULL THEN 'INVALID_PREPARATION' END
FROM reservation_payment_tx preparation
JOIN reservations reservation ON reservation.id = preparation.reservation_id
WHERE preparation.type = 'APPROVAL_PREPARED'
  AND NOT EXISTS (
      SELECT 1 FROM reservation_payment_tx approval
      WHERE approval.type = 'APPROVED'
        AND approval.reservation_id = preparation.reservation_id
        AND approval.provider = preparation.provider
        AND approval.pg_order_number = preparation.pg_order_number
  );
