CREATE TABLE reservation_payment_tx (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    type VARCHAR(32) NOT NULL,
    provider VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL CHECK (amount >= 0),
    attempt_id UUID,
    pg_order_id VARCHAR(64),
    approval_idempotency_key VARCHAR(128),
    payment_id VARCHAR(255),
    cancellation_id VARCHAR(255),
    currency VARCHAR(3) CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(32),
    refund_reason VARCHAR(32),
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reservation_payment_tx_attempt CHECK ((attempt_id IS NULL) = (pg_order_id IS NULL)),
    CONSTRAINT ck_reservation_payment_tx_type CHECK (
        (type = 'APPROVAL_PREPARED' AND amount > 0 AND attempt_id IS NOT NULL AND pg_order_id IS NOT NULL
            AND approval_idempotency_key IS NOT NULL AND payment_id IS NULL AND cancellation_id IS NULL
            AND currency IS NULL AND status IS NULL AND refund_reason IS NULL)
        OR
        (type = 'APPROVED' AND approval_idempotency_key IS NULL AND payment_id IS NOT NULL
            AND cancellation_id IS NULL AND currency IS NOT NULL AND status IS NOT NULL
            AND ((status = 'RESERVATION_CONFIRMED' AND refund_reason IS NULL)
                OR (status = 'REFUND_REQUIRED' AND refund_reason IS NOT NULL
                    AND refund_reason IN ('PAYMENT_MISMATCH', 'RESERVATION_UNAVAILABLE'))))
        OR
        (type = 'CANCELED' AND amount > 0 AND approval_idempotency_key IS NULL AND payment_id IS NOT NULL
            AND cancellation_id IS NOT NULL AND currency IS NOT NULL AND status IS NULL AND refund_reason IS NULL)
    )
);

CREATE INDEX idx_reservation_payment_tx_history ON reservation_payment_tx (reservation_id, id);
CREATE UNIQUE INDEX uk_reservation_payment_tx_attempt
    ON reservation_payment_tx (reservation_id, attempt_id) WHERE type = 'APPROVAL_PREPARED';
CREATE UNIQUE INDEX uk_reservation_payment_tx_prepared_order
    ON reservation_payment_tx (provider, pg_order_id) WHERE type = 'APPROVAL_PREPARED';
CREATE UNIQUE INDEX uk_reservation_payment_tx_approval_key
    ON reservation_payment_tx (provider, approval_idempotency_key) WHERE type = 'APPROVAL_PREPARED';
CREATE UNIQUE INDEX uk_reservation_payment_tx_approved_payment
    ON reservation_payment_tx (provider, payment_id) WHERE type = 'APPROVED';
CREATE UNIQUE INDEX uk_reservation_payment_tx_canceled_payment
    ON reservation_payment_tx (provider, payment_id, cancellation_id) WHERE type = 'CANCELED';

INSERT INTO reservation_payment_tx (
    reservation_id, type, provider, payment_id, amount, currency, status, refund_reason, recorded_at
)
SELECT reservation_id, 'APPROVED', provider, payment_id, amount, currency, status, refund_reason, recorded_at
FROM payment_records
ORDER BY recorded_at, provider, payment_id;

DROP TABLE payment_records;
