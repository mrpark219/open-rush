CREATE TABLE concerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    max_tickets_per_user INTEGER NOT NULL,
    CONSTRAINT ck_concert_max_tickets CHECK (max_tickets_per_user > 0)
);

CREATE TABLE performances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    venue VARCHAR(255) NOT NULL,
    starts_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    booking_opens_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    booking_closes_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_performance_concert FOREIGN KEY (concert_id) REFERENCES concerts (id),
    CONSTRAINT ck_performance_booking_period CHECK (booking_opens_at < booking_closes_at),
    CONSTRAINT ck_performance_booking_deadline CHECK (booking_closes_at <= starts_at)
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    held_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_reservation_performance FOREIGN KEY (performance_id) REFERENCES performances (id),
    CONSTRAINT ck_reservation_user CHECK (user_id > 0),
    CONSTRAINT ck_reservation_hold_period CHECK (held_at < expires_at),
    CONSTRAINT ck_reservation_status CHECK (status IN ('HELD', 'CONFIRMED', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_reservation_confirmation CHECK (
        (status = 'CONFIRMED' AND confirmed_at IS NOT NULL
            AND confirmed_at >= held_at AND confirmed_at < expires_at)
        OR (status <> 'CONFIRMED' AND confirmed_at IS NULL)
    )
);

CREATE TABLE performance_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id BIGINT NOT NULL,
    seat_number VARCHAR(255) NOT NULL,
    price BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    reservation_id BIGINT,
    CONSTRAINT fk_performance_seat_performance FOREIGN KEY (performance_id) REFERENCES performances (id),
    CONSTRAINT fk_performance_seat_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    CONSTRAINT uk_performance_seat_number UNIQUE (performance_id, seat_number),
    CONSTRAINT ck_performance_seat_price CHECK (price >= 0),
    CONSTRAINT ck_performance_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'RESERVED')),
    CONSTRAINT ck_performance_seat_ownership CHECK (
        (status = 'AVAILABLE' AND reservation_id IS NULL)
        OR (status IN ('HELD', 'RESERVED') AND reservation_id IS NOT NULL)
    )
);

CREATE TABLE reservation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    performance_seat_id BIGINT NOT NULL,
    price BIGINT NOT NULL,
    CONSTRAINT fk_reservation_item_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id),
    CONSTRAINT fk_reservation_item_seat FOREIGN KEY (performance_seat_id) REFERENCES performance_seats (id),
    CONSTRAINT uk_reservation_item_seat UNIQUE (reservation_id, performance_seat_id),
    CONSTRAINT ck_reservation_item_price CHECK (price >= 0)
);

CREATE TABLE concert_purchase_quotas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    concert_id BIGINT NOT NULL,
    allocated_quantity INTEGER NOT NULL,
    CONSTRAINT fk_concert_purchase_quota_concert FOREIGN KEY (concert_id) REFERENCES concerts (id),
    CONSTRAINT uk_user_concert_quota UNIQUE (user_id, concert_id),
    CONSTRAINT ck_concert_purchase_quota_user CHECK (user_id > 0),
    CONSTRAINT ck_concert_purchase_quota_quantity CHECK (allocated_quantity >= 0)
);

CREATE INDEX idx_performance_concert ON performances (concert_id);
CREATE INDEX idx_reservation_performance ON reservations (performance_id);
CREATE INDEX idx_reservation_user ON reservations (user_id);
CREATE INDEX idx_reservation_held_expiration ON reservations (expires_at) WHERE status = 'HELD';
CREATE INDEX idx_performance_seat_reservation ON performance_seats (reservation_id);
CREATE INDEX idx_reservation_item_seat ON reservation_items (performance_seat_id);
CREATE INDEX idx_concert_purchase_quota_concert ON concert_purchase_quotas (concert_id);
