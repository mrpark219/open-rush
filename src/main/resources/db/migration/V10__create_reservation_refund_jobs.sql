CREATE TABLE reservation_refund_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approved_payment_transaction_id BIGINT NOT NULL REFERENCES reservation_payment_tx(id),
    status VARCHAR(32) NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_reservation_refund_jobs_approval UNIQUE (approved_payment_transaction_id),
    CONSTRAINT ck_reservation_refund_jobs_status CHECK (
        (status = 'PENDING' AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND completed_at IS NOT NULL)
    )
);

-- 이전 환불 필요 승인과 전액 취소 준비를 작업으로 옮긴다. 거래 이력은 변경하지 않는다.
INSERT INTO reservation_refund_jobs (
    approved_payment_transaction_id, status, completed_at, created_at, modified_at
)
SELECT approval.id,
       CASE WHEN canceled.recorded_at IS NULL THEN 'PENDING' ELSE 'COMPLETED' END,
       canceled.recorded_at,
       COALESCE(prepared.recorded_at, approval.recorded_at),
       COALESCE(canceled.recorded_at, prepared.recorded_at, approval.recorded_at)
FROM reservation_payment_tx approval
LEFT JOIN LATERAL (
    SELECT MIN(preparation.recorded_at) AS recorded_at
    FROM reservation_payment_tx preparation
    WHERE preparation.type = 'CANCEL_PREPARED'
      AND preparation.reservation_id = approval.reservation_id
      AND preparation.provider = approval.provider
      AND preparation.payment_id = approval.payment_id
      AND preparation.amount = approval.amount
      AND preparation.currency = approval.currency
) prepared ON TRUE
LEFT JOIN LATERAL (
    SELECT MIN(cancellation.recorded_at) AS recorded_at
    FROM reservation_payment_tx cancellation
    WHERE cancellation.type = 'CANCELED'
      AND cancellation.reservation_id = approval.reservation_id
      AND cancellation.provider = approval.provider
      AND cancellation.payment_id = approval.payment_id
      AND cancellation.amount = approval.amount
      AND cancellation.currency = approval.currency
) canceled ON TRUE
WHERE approval.type = 'APPROVED'
  AND approval.amount > 0
  AND (approval.status = 'REFUND_REQUIRED' OR prepared.recorded_at IS NOT NULL);
